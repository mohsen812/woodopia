function initializeCapacityTriangles() {

    const triangles =
        document.querySelectorAll(
            ".capacity-triangle"
        );

    console.log(
        "FEEMAAS: Capacity triangles found:",
        triangles.length
    );

    if (!triangles.length) {

        console.warn(
            "FEEMAAS: No capacity triangles found."
        );

        return;

    }

    triangles.forEach(
        triangle => {

            triangle.setAttribute(
                "draggable",
                "true"
            );

            triangle.addEventListener(
                "dragstart",
                startCapacityDrag
            );

            triangle.addEventListener(
                "dragend",
                stopCapacityDrag
            );

            triangle.addEventListener(
                "click",
                () => {

                    selectCapacityTriangle(
                        triangle
                    );

                }
            );

            triangle.addEventListener(
                "dblclick",
                () => {

                    openProjectModal(
                        triangle
                    );

                }
            );

        }
    );

}


// ============================================================
// CAPACITY SELECTION
// ============================================================

function selectCapacityTriangle(
    triangle
) {

    const triangles =
        document.querySelectorAll(
            ".capacity-triangle"
        );

    triangles.forEach(
        item => {

            item.classList.remove(
                "selected"
            );

        }
    );

    triangle.classList.add(
        "selected"
    );

    console.log(
        "FEEMAAS: Capacity triangle selected:",
        triangle.dataset.slot
    );

}


// ============================================================
// CAPACITY DRAG START
// ============================================================

function startCapacityDrag(event) {

    draggedCapacityTriangle =
        event.currentTarget;

    const slot =
        draggedCapacityTriangle.dataset.slot;

    event.dataTransfer.effectAllowed =
        "copy";

    event.dataTransfer.setData(
        "text/plain",
        slot
    );

    selectCapacityTriangle(
        draggedCapacityTriangle
    );

    draggedCapacityTriangle.classList.add(
        "dragging"
    );

    console.log(
        "FEEMAAS: Capacity drag started:",
        slot
    );

}


// ============================================================
// CAPACITY DRAG END
// ============================================================

function stopCapacityDrag() {

    if (draggedCapacityTriangle) {

        draggedCapacityTriangle.classList.remove(
            "dragging"
        );

    }

    draggedCapacityTriangle =
        null;

}


