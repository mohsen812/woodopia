// DRAW WORKSPACE
// ============================================================

function drawWorkspace() {

    const svg =
        document.getElementById(
            "visualCanvas"
        );

    if (!svg) {

        console.warn(
            "FEEMAAS: visualCanvas not found."
        );

        return;

    }

    /*
     * This function draws ONLY infrastructure.
     *
     * It does NOT draw projects.
     * It does NOT draw capacity triangles.
     */

    svg.innerHTML = "";

    svg.setAttribute(
        "viewBox",
        `0 0 ${SVG_WIDTH} ${SVG_HEIGHT}`
    );

    drawBackground(
        svg
    );

    drawCoordinateSystem(
        svg
    );

    WORKSPACE_ZONES.forEach(
        zone => {

            drawZone(
                svg,
                zone
            );

        }
    );

    drawCentralPlaza(
        svg
    );

}


