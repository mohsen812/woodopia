function escapeHtml(
    value
) {

    return String(
        value
    )
        .replace(
            /&/g,
            "&amp;"
        )
        .replace(
            /</g,
            "&lt;"
        )
        .replace(
            />/g,
            "&gt;"
        )
        .replace(
            /"/g,
            "&quot;"
        )
        .replace(
            /'/g,
            "&#039;"
        );

}


// ============================================================
// SVG COORDINATES
// ============================================================

function getSVGPoint(
    svg,
    clientX,
    clientY
) {

    const rect =
        svg.getBoundingClientRect();

    const viewBox =
        svg.viewBox.baseVal;

    const viewBoxWidth =
        viewBox.width ||
        SVG_WIDTH;

    const viewBoxHeight =
        viewBox.height ||
        SVG_HEIGHT;

    const scaleX =
        viewBoxWidth /
        rect.width;

    const scaleY =
        viewBoxHeight /
        rect.height;

    return {

        x:
            (
                clientX -
                rect.left
            ) *
            scaleX,

        y:
            (
                clientY -
                rect.top
            ) *
            scaleY

    };

}


