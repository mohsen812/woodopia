// ============================================================
// WORKSPACE DROP
// ============================================================
//
// Possible destinations:
//
// 1. Zone 1
// 2. Zone 2
// 3. Zone 3
// 4. Zone 4
// 5. Central Decision Plaza
//
// Outside these areas = invalid.
// ============================================================

function handleWorkspaceDrop(event) {

    event.preventDefault();

    if (!draggedCapacityTriangle) {

        return;

    }

    const svg =
        document.getElementById(
            "visualCanvas"
        );

    if (!svg) {

        return;

    }

    const point =
        getSVGPoint(
            svg,
            event.clientX,
            event.clientY
        );

    const zone =
        detectPointZone(
            point.x,
            point.y
        );

    const isCentral =
        isPointInsideCentralPlaza(
            point.x,
            point.y
        );

    console.log(
        "FEEMAAS: Capacity dropped:",
        {
            slot:
                draggedCapacityTriangle.dataset.slot,

            x:
                point.x,

            y:
                point.y,

            zone:
                zone
                    ? zone.id
                    : null,

            central:
                isCentral
        }
    );

    if (!zone && !isCentral) {

        console.log(
            "FEEMAAS: Invalid drop location."
        );

        return;

    }

    const slot =
        Number(
            draggedCapacityTriangle.dataset.slot
        );

    window.pendingProjectCreation = {

        slot: slot,

        zoneId:
            zone
                ? zone.id
                : null,

        decisionPlaza:
            isCentral,

        position_x:
            Number(
                point.x -
                SVG_CENTER_X
            ),

        position_y:
            Number(
                point.y -
                SVG_CENTER_Y
            )

    };

    openProjectModal(
        draggedCapacityTriangle
    );

}


// ============================================================
// DETECT CUSTOMER ZONE
// ============================================================

function detectPointZone(
    x,
    y
) {

    for (
        const zone of WORKSPACE_ZONES
    ) {

        const inside =
            x >= zone.x &&
            x <= zone.x + zone.width &&
            y >= zone.y &&
            y <= zone.y + zone.height;

        if (inside) {

            return zone;

        }

    }

    return null;

}


// ============================================================
// CENTRAL PLAZA DETECTION
// ============================================================

function isPointInsideCentralPlaza(
    x,
    y
) {

    const dx =
        x -
        CENTRAL_PLAZA.x;

    const dy =
        y -
        CENTRAL_PLAZA.y;

    const distance =
        Math.sqrt(
            dx * dx +
            dy * dy
        );

    return (
        distance <=
        CENTRAL_PLAZA.radius
    );

}


