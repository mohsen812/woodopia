// ============================================================
// FEEMAAS WORKSPACE ENGINE
// Version 8
//
// Architecture:
// ------------------------------------------------------------
// 1. Capacity Layer
//    - Exactly 5 initial customer triangles
//    - Each triangle represents one project capacity slot
//    - Consumed slots disappear from the palette
//
// 2. Workspace Layer
//    - 4 customer/workflow zones
//    - Central Decision Plaza
//    - Coordinate system
//
// 3. Project Visual Layer
//    - Real project shapes
//    - Persistent position
//    - Selection
//    - Drag
//    - Double-click project information
//
// 4. Decision Plaza
//    - A project can wait for consultant decision
//    - Consultant test controls are generated by JS
//    - Consultant can move project to a zone
//
// IMPORTANT:
// Capacity triangles and Project Visuals are NOT the same thing.
// ============================================================


