// ============================================================
// MOVE PROJECT TO ZONE
// ============================================================
//
// Temporary consultant engine.
//
// For now we move the visual to the
// center of the selected zone and persist
// its position.
//
// Later this exact operation can be connected
// to a dedicated backend zone-assignment API.
// ============================================================

async function moveProjectToZone(
    project,
    visual,
    zoneId
) {

    const zone =
        WORKSPACE_ZONES.find(
            item =>
                item.id === zoneId
        );

    if (!zone) {

        return;

    }

    const newX =
        (
            zone.x +
            zone.width / 2
        ) -
        SVG_CENTER_X;

    const newY =
        (
            zone.y +
            zone.height / 2
        ) -
        SVG_CENTER_Y;

    visual.position_x =
        Number(
            newX.toFixed(2)
        );

    visual.position_y =
        Number(
            newY.toFixed(2)
        );

    const element =
        findVisualElement(
            visual.id
        );

    if (element) {

        updateVisualPosition(
            element,
            newX,
            newY
        );

    }

    await saveVisualPosition();

    const panel =
        document.getElementById(
            "feemaasConsultantPanel"
        );

    if (panel) {

        panel.classList.add(
            "hidden"
        );

    }

    console.log(
        "FEEMAAS Consultant decision:",
        {
            project:
                project.id,

            visual:
                visual.id,

            zone:
                zone.id
        }
    );

}


// ============================================================
// ESCAPE HTML
