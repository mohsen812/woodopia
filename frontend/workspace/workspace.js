// ============================================================
// DRAW PROJECT VISUAL
// ============================================================

function drawVisual(
    visual,
    clearExisting = true
) {

    if (!visual) {

        return;

    }

    const svg =
        document.getElementById(
            "visualCanvas"
        );

    if (!svg) {

        return;

    }

    if (clearExisting) {

        removeExistingVisuals(
            svg
        );

    }

    visual.position_x =
        clamp(
            Number(
                visual.position_x
            ) || 0,
            -350,
            350
        );

    visual.position_y =
        clamp(
            Number(
                visual.position_y
            ) || 0,
            -200,
            200
        );

    const shapeType =
        String(
            visual.shape_type || ""
        ).toLowerCase();

    currentVisual =
        visual;

    switch (shapeType) {

        case "triangle":

            createTriangle(
                svg,
                visual
            );

            break;

        case "square":

            createSquare(
                svg,
                visual
            );

            break;

        case "hexagon":

            createHexagon(
                svg,
                visual
            );

            break;

        default:

            console.warn(
                "FEEMAAS: Unsupported visual shape:",
                visual.shape_type
            );

    }

}


