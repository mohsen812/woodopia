// ============================================================
// CREATE PROJECT
// ============================================================

async function handleCreateProject() {

    const titleInput =
        document.getElementById(
            "projectTitleInput"
        );

    const descriptionInput =
        document.getElementById(
            "projectDescriptionInput"
        );

    const quantityInput =
        document.getElementById(
            "projectQuantityInput"
        );

    const budgetInput =
        document.getElementById(
            "projectBudgetInput"
        );

    const pending =
        window.pendingProjectCreation;

    if (!pending) {

        alert(
            "ابتدا یک مثلث پروژه را انتخاب کنید."
        );

        return;

    }

    const title =
        titleInput
            ? titleInput.value.trim()
            : "";

    const description =
        descriptionInput
            ? descriptionInput.value.trim()
            : "";

    const quantity =
        quantityInput
            ? quantityInput.value
            : "";

    const budget =
        budgetInput
            ? budgetInput.value
            : "";

    if (!title) {

        alert(
            "لطفاً نام پروژه را وارد کنید."
        );

        return;

    }

    const payload = {

        title: title,

        description: description,

        customer: 1,

        created_by: 1,

        status: "draft"

    };

    console.log(
        "FEEMAAS: Creating project",
        {
            payload,
            pending,
            quantity,
            budget
        }
    );

    try {

        const response =
            await fetch(
                API_URL,
                {

                    method: "POST",

                    headers: {

                        "Content-Type":
                            "application/json"

                    },

                    body:
                        JSON.stringify(
                            payload
                        )

                }
            );

        if (!response.ok) {

            throw new Error(
                `Project creation failed: ${response.status}`
            );

        }

        const project =
            await response.json();

        console.log(
            "FEEMAAS: Project created:",
            project
        );

        currentProject =
            project;

        closeProjectModal();

        /*
         * The backend currently creates the
         * initial visual automatically.
         *
         * Therefore we now locate that visual
         * and synchronize:
         *
         * - capacity slot
         * - position
         */

        const projectWithVisual =
            await fetchProjectById(
                project.id
            );

        if (
            projectWithVisual
        ) {

            const visual =
                getFirstProjectVisual(
                    projectWithVisual
                );

            if (visual) {

                await synchronizeNewVisual(
                    visual,
                    pending
                );

            }

        }

        alert(
            "پروژه با موفقیت ثبت شد"
        );

        /*
         * Reload projects without
         * resetting capacity state incorrectly.
         */

        await loadProjects();

    }

    catch (error) {

        console.error(
            "FEEMAAS Create Project Error:",
            error
        );

        alert(
            "خطا در ثبت پروژه"
        );

    }

}


// ============================================================
// FETCH SINGLE PROJECT
// ============================================================

async function fetchProjectById(
    projectId
) {

    try {

        const response =
            await fetch(
                `${API_URL}${projectId}/`
            );

        if (!response.ok) {

            return null;

        }

        return await response.json();

    }

    catch (error) {

        console.error(
            "FEEMAAS: Project fetch error:",
            error
        );

        return null;

    }

}


// ============================================================
// GET FIRST VISUAL
// ============================================================

function getFirstProjectVisual(
    project
) {

    if (
        !project ||
        !Array.isArray(
            project.zones
        )
    ) {

        return null;

    }

    for (
        const zone of project.zones
    ) {

        if (
            !zone ||
            !Array.isArray(
                zone.visuals
            )
        ) {

            continue;

        }

        if (
            zone.visuals.length
        ) {

            return zone.visuals[0];

        }

    }

    return null;

}


// ============================================================
// SYNCHRONIZE NEW VISUAL
// ============================================================
//
// This is important because the current
// backend automatically creates the visual.
//
// We PATCH it immediately so the visual
// represents the actual capacity slot
// and actual drop position.
// ============================================================

async function synchronizeNewVisual(
    visual,
    pending
) {

    if (
        !visual ||
        !visual.id ||
        !pending
    ) {

        return;

    }

    const payload = {

        position_x:
            Number(
                pending.position_x
            ),

        position_y:
            Number(
                pending.position_y
            ),

        visual_data: {

            ...(visual.visual_data || {}),

            capacity_slot:
                Number(
                    pending.slot
                ),

            engine_version:
                "phase_2_v8",

            workspace_location:
                pending.decisionPlaza
                    ? "decision_plaza"
                    : "zone",

            workspace_zone:
                pending.zoneId || null

        }

    };

    try {

        const response =
            await fetch(
                `${API_URL}visuals/${visual.id}/`,
                {

                    method: "PATCH",

                    headers: {

                        "Content-Type":
                            "application/json"

                    },

                    body:
                        JSON.stringify(
                            payload
                        )

                }
            );

        if (!response.ok) {

            console.warn(
                "FEEMAAS: Visual synchronization failed:",
                response.status
            );

            return;

        }

        console.log(
            "FEEMAAS: New visual synchronized."
        );

    }

    catch (error) {

        console.error(
            "FEEMAAS: Visual synchronization error:",
            error
        );

    }

}


// ============================================================
// LOAD ALL PROJECTS
// ============================================================

async function loadProjects() {

    try {

        const response =
            await fetch(
                API_URL
            );

        if (!response.ok) {

            throw new Error(
                `API error: ${response.status}`
            );

        }

        const projects =
            await response.json();

        if (
            !Array.isArray(
                projects
            )
        ) {

            throw new Error(
                "Projects response is not an array."
            );

        }

        currentProjects =
            projects;

        console.log(
            "FEEMAAS: Projects loaded:",
            currentProjects
        );

        /*
         * IMPORTANT:
         *
         * Do not redraw the entire page
         * in a way that resets capacity
         * or visual state.
         */

        renderWorkspaceState();

    }

    catch (error) {

        console.error(
            "FEEMAAS API Error:",
            error
        );

        /*
         * Workspace itself must still work
         * even if API is temporarily unavailable.
         */

        renderWorkspaceState();

    }

}


// ============================================================
